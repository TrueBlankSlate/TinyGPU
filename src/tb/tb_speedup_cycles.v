`timescale 1ns / 1ps

// Cycle-count comparison: same CVA6+TinyGPU SoC, same 4x4 matrix A, run
// through TWO independent cold boots back to back --
//
//   Phase 1 (OFFLOAD): CVA6 boots, loads A via vle64.v, issues ONE vmacc.vv
//   (offloaded to TinyGPU over CV-X-IF), and TinyGPU streams the 4x4 result
//   back over its own AXI4 write master. Timed from reset release to the
//   last writeback word landing in memory.
//
//   Phase 2 (SCALAR): the boot memory is overwritten with a plain RV64IM
//   program -- no custom/vector opcodes at all -- that computes the exact
//   same C = A x A on CVA6's own scalar pipeline (16 outputs x 4
//   multiply-accumulates each, straight-line/unrolled, ld+ld+mul+add x4 per
//   output + one sd), using CVA6's M-extension `mul`. The whole SoC is then
//   reset again (a real cold reboot, same DUT instance) and timed the same
//   way, from reset release to its own last store landing.
//
// Both timings use the same $time/CLK_PERIOD arithmetic, so the ratio
// (scalar_cycles / offload_cycles) is a direct, apples-to-apples cycle-count
// speedup of "offload the matmul to TinyGPU" vs. "just run it on CVA6",
// entirely in simulation -- no hardware needed.
//
// The scalar RV64IM program is not hand-encoded like the offload one --
// it's assembled at elaboration time from little encoder functions
// (enc_utype/enc_itype/enc_stype/enc_rtype below), following the standard
// RISC-V bit layouts, and generated by looping over i/j/k in the initial
// block. This is the only practical way to get ~300 correct instructions
// without hand-computing every opcode.
module tb_speedup_cycles;

  localparam integer CLK_PERIOD = 10; // 100 MHz, matches `always #5 clk = ~clk;` below

  localparam [63:0] BOOT_ADDR          = 64'h0000_0000_8000_0000;
  localparam [63:0] MAT_ADDR           = 64'h0000_0000_8000_1000;
  localparam [63:0] MUL_RESULT_ADDR    = 64'h0000_0000_8000_2000; // offload (TinyGPU) writeback
  localparam [63:0] SCALAR_RESULT_ADDR = 64'h0000_0000_8000_5000; // scalar (CVA6-only) writeback

  reg clk = 0;
  reg rst_ni = 0;
  always #5 clk = ~clk; // 100 MHz

  // ---- NOC/AXI4 -- same single shared, arbitrated bus as tb_cva6_boot.v ----
  wire [4:0]  noc_aw_id;   wire [63:0] noc_aw_addr; wire [7:0] noc_aw_len;
