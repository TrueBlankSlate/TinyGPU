
`timescale 1ns / 1ps

module top(

    //==========================================================
    // FPGA Inputs
    //==========================================================

    input wire clk,
    input wire rst,

    //==========================================================
    // FPGA Outputs
    //==========================================================

    output wire [3:0] led

);

    //==========================================================
    // Reset
    //==========================================================

    // Arty A7 reset button is ACTIVE-LOW.
    // Internal modules use ACTIVE-HIGH reset.
    wire rst_int;

    assign rst_int = ~rst;


    //==========================================================
    // Test Module Signals
    //==========================================================

    wire        we;
    wire [2:0]  func3;
    wire [5:0]  instr_id;

    wire [255:0] mat_a;
    wire [255:0] mat_b;


    //==========================================================
    // Accumulator Reset
    //==========================================================

    assign acc_rst = 1'b0;

    wire acc_rst;


    //==========================================================
    // Cache -> Register Files
    //==========================================================

    wire [63:0] a0;
    wire [63:0] a1;
    wire [63:0] a2;
    wire [63:0] a3;

    wire [63:0] b0;
    wire [63:0] b1;
    wire [63:0] b2;
    wire [63:0] b3;


    //==========================================================
    // Register Files -> ALUs
    //==========================================================

    wire [63:0] vs1_0;
    wire [63:0] vs2_0;

    wire [63:0] vs1_1;
    wire [63:0] vs2_1;

    wire [63:0] vs1_2;
    wire [63:0] vs2_2;

    wire [63:0] vs1_3;
    wire [63:0] vs2_3;


    //==========================================================
    // ALU Outputs
    //==========================================================

    wire [63:0] vd0;
    wire [63:0] vd1;
    wire [63:0] vd2;
    wire [63:0] vd3;


    //==========================================================
    // TEST INPUT GENERATOR
    //==========================================================

    test TEST(

        .mat_a(mat_a),
        .mat_b(mat_b),

        .we(we),
        .instr_id(instr_id),
        .func3(func3)

    );


    //==========================================================
    // CACHE
    //==========================================================

    cache CACHE(

        .clk(clk),
        .rst(rst_int),

        .func3(func3),
        .instr_id(instr_id),

        .mat_a(mat_a),
        .mat_b(mat_b),

        .we(we),

        .a0(a0),
        .a1(a1),
        .a2(a2),
        .a3(a3),

        .b0(b0),
        .b1(b1),
        .b2(b2),
        .b3(b3)

    );


    //==========================================================
    // REGISTER FILE 0
    //==========================================================

    RegisterFile RF0(

        .clk(clk),
        .rst(rst_int),

        .we(we),

        .vs1_in(a0),
        .vs2_in(b0),

        .vs1_out(vs1_0),
        .vs2_out(vs2_0)

    );


    //==========================================================
    // REGISTER FILE 1
    //==========================================================

    RegisterFile RF1(

        .clk(clk),
        .rst(rst_int),

        .we(we),

        .vs1_in(a1),
        .vs2_in(b1),

        .vs1_out(vs1_1),
        .vs2_out(vs2_1)

    );


    //==========================================================
    // REGISTER FILE 2
    //==========================================================

    RegisterFile RF2(

        .clk(clk),
        .rst(rst_int),

        .we(we),

        .vs1_in(a2),
        .vs2_in(b2),

        .vs1_out(vs1_2),
        .vs2_out(vs2_2)

    );


    //==========================================================
    // REGISTER FILE 3
    //==========================================================

    RegisterFile RF3(

        .clk(clk),
        .rst(rst_int),

        .we(we),

        .vs1_in(a3),
        .vs2_in(b3),

        .vs1_out(vs1_3),
        .vs2_out(vs2_3)

    );


    //==========================================================
    // ALU 0
    //==========================================================

    ALU ALU0(

        .clk(clk),
        .rst(rst_int),

        .acc_rst(acc_rst),

        .func3(func3),
        .instr_id(instr_id),

        .we(we),

        .vs1(vs1_0),
        .vs2(vs2_0),

        .vd(vd0)

    );


    //==========================================================
    // ALU 1
    //==========================================================

    ALU ALU1(

        .clk(clk),
        .rst(rst_int),

        .acc_rst(acc_rst),

        .func3(func3),
        .instr_id(instr_id),

        .we(we),

        .vs1(vs1_1),
        .vs2(vs2_1),

        .vd(vd1)

    );


    //==========================================================
    // ALU 2
    //==========================================================

    ALU ALU2(

        .clk(clk),
        .rst(rst_int),

        .acc_rst(acc_rst),

        .func3(func3),
        .instr_id(instr_id),

        .we(we),

        .vs1(vs1_2),
        .vs2(vs2_2),

        .vd(vd2)

    );


    //==========================================================
    // ALU 3
    //==========================================================

    ALU ALU3(

        .clk(clk),
        .rst(rst_int),

        .acc_rst(acc_rst),

        .func3(func3),
        .instr_id(instr_id),

        .we(we),

        .vs1(vs1_3),
        .vs2(vs2_3),

        .vd(vd3)

    );


    //==========================================================
    // DIRECT DEBUG OUTPUT
    //==========================================================

    writeback WB(

    .v0(vd0),
    .v1(vd1),
    .v2(vd2),
    .v3(vd3),

    .clk(clk),
    .rst(rst_int),

    .led(led)

);

endmodule